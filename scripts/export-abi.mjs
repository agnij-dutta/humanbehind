// Exports Foundry ABIs into packages/core/src/abi.ts as `as const` literals
// so viem infers exact types. Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = (c, f = c) => JSON.parse(readFileSync(path.join(root, 'contracts/out', `${f}.sol`, `${c}.json`), 'utf8'));

const contracts = {
  humanBindingRegistryAbi: out('HumanBindingRegistry'),
  agentIdentityRegistryAbi: out('AgentIdentityRegistry'),
};

let src = '// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.\n\n';
for (const [name, art] of Object.entries(contracts)) {
  src += `export const ${name} = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
}
writeFileSync(path.join(root, 'packages/core/src/abi.ts'), src);

// Bytecode for local deploys from TS (e2e script).
const bytecode = {
  HumanBindingRegistry: out('HumanBindingRegistry').bytecode.object,
  AgentIdentityRegistry: out('AgentIdentityRegistry').bytecode.object,
  AnonAadhaar: out('AnonAadhaar').bytecode.object,
  AnonAadhaarGroth16Verifier: out('Verifier', 'AnonAadhaarGroth16Verifier').bytecode.object,
};
const abis = {
  AnonAadhaar: out('AnonAadhaar').abi,
  AnonAadhaarGroth16Verifier: out('Verifier', 'AnonAadhaarGroth16Verifier').abi,
};
writeFileSync(path.join(root, 'scripts/artifacts.json'), JSON.stringify({ bytecode, abis }, null, 2));
console.log('wrote packages/core/src/abi.ts and scripts/artifacts.json');
